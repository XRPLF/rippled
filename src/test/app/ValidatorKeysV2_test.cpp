    void
    testKeyType(KeyTypeTestData const& testData, beast::Journal const& journal)
    {
        testcase(testData.name);

        // Keys/ID when using [validation_seed]
        SecretKey const seedSecretKey = generateSecretKey(
            testData.keyType, *parseBase58<Seed>(testData.seed));
        PublicKey const seedPublicKey =
            derivePublicKey(testData.keyType, seedSecretKey);
        NodeID const seedNodeID = calcNodeID(seedPublicKey);

        // Keys when using [validation_token]
        auto const tokenSecretKey = *parseBase58<SecretKey>(
            TokenType::NodePrivate, testData.tokenSecretStr);

        auto const tokenPublicKey =
            derivePublicKey(testData.keyType, tokenSecretKey);

        BEAST_EXPECT(1 == 1);

        auto const m =
            deserializeManifest(base64_decode(testData.tokenManifest));
        BEAST_EXPECT(m);
        NodeID const tokenNodeID = calcNodeID(m->masterKey);

        {
            // No config -> no key but valid
            Config c;
            ValidatorKeys k{c, journal};
            BEAST_EXPECT(!k.keys);
            BEAST_EXPECT(k.manifest.empty());
            BEAST_EXPECT(!k.configInvalid());
        }
        {
            // validation seed section -> empty manifest and valid seeds
            Config c;
            c.section(SECTION_VALIDATION_SEED).append(testData.seed);
            c.section(SECTION_VALIDATOR_KEY_TYPE).append(testData.name);

            ValidatorKeys k{c, journal};
            if (BEAST_EXPECT(k.keys))
            {
                BEAST_EXPECT(k.keys->publicKey == seedPublicKey);
                BEAST_EXPECT(k.keys->secretKey == seedSecretKey);
            }
            BEAST_EXPECT(k.nodeID == seedNodeID);
            BEAST_EXPECT(k.manifest.empty());
            BEAST_EXPECT(!k.configInvalid());
        }

        {
            // validation seed bad seed -> invalid
            Config c;
            c.section(SECTION_VALIDATION_SEED).append("badseed");

            ValidatorKeys k{c, journal};
            BEAST_EXPECT(k.configInvalid());
            BEAST_EXPECT(!k.keys);
            BEAST_EXPECT(k.manifest.empty());
        }

        {
            // validator token
            Config c;
            c.section(SECTION_VALIDATOR_TOKEN).append(testData.tokenBlob);
            c.section(SECTION_VALIDATOR_KEY_TYPE).append(testData.name);
            ValidatorKeys k{c, journal};

            if (BEAST_EXPECT(k.keys))
            {
                BEAST_EXPECT(k.keys->publicKey == tokenPublicKey);
                BEAST_EXPECT(k.keys->secretKey == tokenSecretKey);
            }
            BEAST_EXPECT(k.nodeID == tokenNodeID);
            BEAST_EXPECT(k.manifest == testData.tokenManifest);
            BEAST_EXPECT(!k.configInvalid());
        }
        {
            // invalid validator token
            Config c;
            c.section(SECTION_VALIDATOR_TOKEN).append("badtoken");
            c.section(SECTION_VALIDATOR_KEY_TYPE).append(testData.name);
            ValidatorKeys k{c, journal};
            BEAST_EXPECT(k.configInvalid());
            BEAST_EXPECT(!k.keys);
            BEAST_EXPECT(k.manifest.empty());
        }

        {
            // Cannot specify both
            Config c;
            c.section(SECTION_VALIDATION_SEED).append(testData.seed);
            c.section(SECTION_VALIDATOR_TOKEN).append(testData.tokenBlob);
            ValidatorKeys k{c, journal};

            BEAST_EXPECT(k.configInvalid());
            BEAST_EXPECT(!k.keys);
            BEAST_EXPECT(k.manifest.empty());
        }

        {
            // Token manifest and private key must match
            Config c;
            c.section(SECTION_VALIDATOR_TOKEN)
                .append(testData.invalidTokenBlob);
            c.section(SECTION_VALIDATOR_KEY_TYPE).append(testData.name);
            ValidatorKeys k{c, journal};

            BEAST_EXPECT(k.configInvalid());
            BEAST_EXPECT(!k.keys);
            BEAST_EXPECT(k.manifest.empty());
        }
    }

