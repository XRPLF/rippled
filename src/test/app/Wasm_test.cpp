std::vector<uint8_t>
hexToBytes(std::string const& hex)
{
    auto const ws = boost::algorithm::unhex(hex);
    return Bytes(ws.begin(), ws.end());
}

template <class IT, class T>
unsigned
uleb128(IT& it, T val)
{
    unsigned count = 0;
    do
    {
        std::uint8_t byte = val & 0x7f;
        val >>= 7;
        if (val)
            byte |= 0x80;
        *it++ = byte;
        ++count;
    } while (val != 0);

    return count;
}

template <class IT>
std::pair<std::uint64_t, unsigned>
uleb128(IT&& it)
{
    static_assert(sizeof(*it) == 1, "invalid iterator type");
    std::uint64_t val = 0;
    std::uint64_t byte = 0;
    unsigned shift = 0;
    unsigned count = 0;

    do
    {
        if (shift > (sizeof(std::uint64_t) * 8) - 7)
            return {0, 0};
        byte = *it++;
        val |= (byte & 0x7F) << shift;
        shift += 7;
        ++count;
    } while (byte >= 0x80);

    return {val, count};
}

