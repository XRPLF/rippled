namespace xrpl {

class SetPasskeyList : public Transactor
{
public:
    static constexpr auto kConsequencesFactory = ConsequencesFactoryType::Blocker;

    explicit SetPasskeyList(ApplyContext& ctx) : Transactor(ctx)
    {
    }

    static NotTEC
    preflight(PreflightContext const& ctx);

    TER
    doApply() override;

    /**
     * Removes the passkey list `sle` owned by `owner`, as AccountDelete does.
     */
    static TER
    deleteSLE(ApplyView& view, SLE::pointer const& sle, AccountID const& owner, beast::Journal j);

    void
    visitInvariantEntry(bool isDelete, SLE::ConstRef before, SLE::ConstRef after) override;

    [[nodiscard]] bool
    finalizeInvariants(
        STTx const& tx,
        TER result,
        XRPAmount fee,
        ReadView const& view,
        beast::Journal const& j) override;
};

using PasskeyListSet = SetPasskeyList;

}  // namespace xrpl
