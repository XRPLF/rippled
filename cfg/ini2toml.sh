#!/usr/bin/env bash
#
# ini2toml.sh - Convert xrpld INI configuration files to TOML format
#
# Usage: ./ini2toml.sh input.cfg [output.toml]
#        If output.toml is not specified, outputs to stdout

set -e

if [[ $# -lt 1 ]]; then
    echo "Usage: $0 input.cfg [output.toml]" >&2
    echo "       Converts xrpld INI config to TOML format, preserving comments." >&2
    exit 1
fi

INPUT_FILE="$1"
OUTPUT_FILE="${2:-/dev/stdout}"

if [[ ! -f "$INPUT_FILE" ]]; then
    echo "Error: Input file '$INPUT_FILE' not found." >&2
    exit 1
fi

# Create temp files for storing parsed data
TMPDIR="${TMPDIR:-/tmp}"
ROOT_KEYS_FILE=$(mktemp "${TMPDIR}/ini2toml_root_keys.XXXXXX")
ROOT_ITEMS_FILE=$(mktemp "${TMPDIR}/ini2toml_root_items.XXXXXX")
SECTIONS_FILE=$(mktemp "${TMPDIR}/ini2toml_sections.XXXXXX")
SECTION_ORDER_FILE=$(mktemp "${TMPDIR}/ini2toml_section_order.XXXXXX")

cleanup() {
    rm -f "$ROOT_KEYS_FILE" "$ROOT_ITEMS_FILE" "$SECTIONS_FILE" "$SECTION_ORDER_FILE"
}
trap cleanup EXIT

current_section=""

# Function to determine if a value needs quoting in TOML
format_value() {
    local value="$1"
    value="$(echo "$value" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"

    if [[ "$value" =~ ^-?[0-9]+$ ]]; then
        echo "$value"
    elif [[ "$value" =~ ^-?[0-9]+\.[0-9]+$ ]]; then
        echo "$value"
    elif [[ "$value" =~ ^(true|false)$ ]]; then
        echo "$value"
    else
        value="${value//\\/\\\\}"
        value="${value//\"/\\\"}"
        echo "\"$value\""
    fi
}

# First pass: parse the file
while IFS= read -r line || [[ -n "$line" ]]; do
    line="${line%"${line##*[![:space:]]}"}"

    # Skip empty lines and comments for parsing
    [[ -z "$line" ]] && continue
    [[ "$line" =~ ^[[:space:]]*# ]] && continue

    # Section header
    if [[ "$line" =~ ^\[([^\]]+)\]$ ]]; then
        current_section="${BASH_REMATCH[1]}"
        # Add to section order if not already present
        if ! grep -qxF "$current_section" "$SECTION_ORDER_FILE" 2>/dev/null; then
            echo "$current_section" >> "$SECTION_ORDER_FILE"
        fi
        continue
    fi

    # Key=value pair
    if [[ "$line" =~ ^([^=]+)=(.*)$ ]]; then
        key="$(echo "${BASH_REMATCH[1]}" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"
        value="${BASH_REMATCH[2]}"
        if [[ -z "$current_section" ]]; then
            echo "${key}=${value}" >> "$ROOT_KEYS_FILE"
        else
            echo "${current_section}|KV|${key}=${value}" >> "$SECTIONS_FILE"
        fi
        continue
    fi

    # Standalone value
    value="$(echo "$line" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"
    if [[ -n "$value" ]]; then
        if [[ -z "$current_section" ]]; then
            echo "$value" >> "$ROOT_ITEMS_FILE"
        else
            echo "${current_section}|ITEM|${value}" >> "$SECTIONS_FILE"
        fi
    fi
done < "$INPUT_FILE"

# Second pass: output TOML
{
    echo "# Converted from $INPUT_FILE"
    echo "# Generated by ini2toml.sh on $(date)"
    echo ""

    # Output root-level keys first (required by TOML)
    if [[ -f "$ROOT_KEYS_FILE" ]]; then
        while IFS= read -r kv_line; do
            if [[ "$kv_line" =~ ^([^=]+)=(.*)$ ]]; then
                key="${BASH_REMATCH[1]}"
                value="${BASH_REMATCH[2]}"
                formatted_value=$(format_value "$value")
                echo "${key} = ${formatted_value}"
            fi
        done < "$ROOT_KEYS_FILE"
    fi

    # Output root-level standalone items as an array if any
    if [[ -s "$ROOT_ITEMS_FILE" ]]; then
        echo ""
        echo "# Root-level items (may need manual review)"
        echo "items = ["
        while IFS= read -r item; do
            formatted_value=$(format_value "$item")
            echo "    ${formatted_value},"
        done < "$ROOT_ITEMS_FILE"
        echo "]"
    fi

    # Collect server port names (items listed under [server] section)
    SERVER_PORTS_FILE=$(mktemp "${TMPDIR}/ini2toml_server_ports.XXXXXX")
    if grep -q "^server|ITEM|" "$SECTIONS_FILE" 2>/dev/null; then
        grep "^server|ITEM|" "$SECTIONS_FILE" | cut -d'|' -f3 > "$SERVER_PORTS_FILE"
    fi

    # FIRST PASS: Output sections that become top-level key-value pairs
    # (sections with only standalone items, not [server], and not server ports)
    if [[ -f "$SECTION_ORDER_FILE" ]]; then
        while IFS= read -r section; do
            [[ -z "$section" ]] && continue
            # Skip server section
            [[ "$section" == "server" ]] && continue
            # Skip server ports (they become [server.ports.*])
            grep -qxF "$section" "$SERVER_PORTS_FILE" 2>/dev/null && continue
            # Skip sections that have key=value pairs (they need [section] headers)
            grep -q "^${section}|KV|" "$SECTIONS_FILE" 2>/dev/null && continue

            # Only process sections with standalone items only
            if grep -q "^${section}|ITEM|" "$SECTIONS_FILE" 2>/dev/null; then
                item_count=$(grep -c "^${section}|ITEM|" "$SECTIONS_FILE")
                if [[ "$item_count" -eq 1 ]]; then
                    # Single item becomes a simple key-value pair
                    item=$(grep "^${section}|ITEM|" "$SECTIONS_FILE" | head -1 | cut -d'|' -f3)
                    formatted_value=$(format_value "$item")
                    echo "${section} = ${formatted_value}"
                else
                    # Multiple items become an array
                    echo "${section} = ["
                    grep "^${section}|ITEM|" "$SECTIONS_FILE" | while IFS='|' read -r _ _ item; do
                        formatted_value=$(format_value "$item")
                        echo "    ${formatted_value},"
                    done
                    echo "]"
                fi
            fi
        done < "$SECTION_ORDER_FILE"
    fi

    # SECOND PASS: Output sections with [section] headers
    if [[ -f "$SECTION_ORDER_FILE" ]]; then
        while IFS= read -r section; do
            [[ -z "$section" ]] && continue

            # Check if this section is a server port (listed under [server])
            is_server_port=false
            if grep -qxF "$section" "$SERVER_PORTS_FILE" 2>/dev/null; then
                is_server_port=true
            fi

            # Skip [server] section (its items are port references)
            [[ "$section" == "server" ]] && continue

            # Skip sections that only have items and no KV pairs (already output above)
            # unless they're server ports
            if ! $is_server_port; then
                if grep -q "^${section}|ITEM|" "$SECTIONS_FILE" 2>/dev/null; then
                    if ! grep -q "^${section}|KV|" "$SECTIONS_FILE" 2>/dev/null; then
                        continue
                    fi
                fi
            fi

            # Output section with key=value pairs as [section]
            if grep -q "^${section}|KV|" "$SECTIONS_FILE" 2>/dev/null; then
                echo ""
                # Sections listed under [server] become [server.ports.section_name]
                if $is_server_port; then
                    echo "[server.ports.${section}]"
                else
                    echo "[$section]"
                fi
                grep "^${section}|KV|" "$SECTIONS_FILE" | while IFS='|' read -r _ _ kv_line; do
                    if [[ "$kv_line" =~ ^([^=]+)=(.*)$ ]]; then
                        key="${BASH_REMATCH[1]}"
                        value="${BASH_REMATCH[2]}"
                        formatted_value=$(format_value "$value")
                        echo "${key} = ${formatted_value}"
                    fi
                done
            fi
        done < "$SECTION_ORDER_FILE"
    fi

    rm -f "$SERVER_PORTS_FILE"

} > "$OUTPUT_FILE"

if [[ "$OUTPUT_FILE" != "/dev/stdout" ]]; then
    echo "Converted '$INPUT_FILE' to '$OUTPUT_FILE'"
fi
